"""Keep the conformance counts quoted in the prose equal to the report's.

``docs/conformance.json`` is generated by :mod:`scripts.conformance_report` and
its ``counts`` object is the single authority for how many checks the suite
runs, across how many domains, against how many normative designations and
how many further published sources. Pages that quote those integers used to
type them out, and three of them fell a release behind: the landing page said
427 checks while *Why phonometry* still said 371.

This script used to read them by matching a regular expression against the
report's headline sentence, which made an English sentence a wire format:
three files parsed it, in two languages, and each carried an error message
telling you to go and update the other two. Reading a field out of a document
that exists to be read is what replaced that.

The Astro page bodies import the numbers from
``site/src/data/conformance-stats.mjs``, so they cannot drift. What is left is
the text that has no build step to interpolate through: the plain-markdown
mirror under ``docs/``, the ``README.md`` and generated ``README_PYPI.md`` at
the repository root, the README of the PyOctaveBand transition stub, the
``.zenodo.json`` description, and the YAML frontmatter of the site pages (the
landing-page meta descriptions and the JSON-LD blocks on the conformance
pages, which are static data parsed before MDX ever runs). Those used to be
edited by hand after every change that moved a count.

The READMEs are why the file set reaches the repository root at all, instead
of stopping at ``docs/``. They sat outside it, said "more than 250 standards"
while the report said 365, and the gate called the corpus consistent
throughout. The PyPI one is the worse of the two to get wrong: PyPI freezes a
long description at upload, so a count that is stale on release day stays
published.

This script owns them instead. It has two modes over **one** list of patterns,
so the two can never disagree:

* the default read-only check, which reports every stale count and exits
  non-zero. This is the CI gate;
* ``--write`` (``--fix``), which substitutes the authoritative value in place.
  It replaces the span of the captured digits and nothing else, so the
  surrounding prose, and any other number that happens to share the value,
  are left untouched. ``make conformance`` runs it right after regenerating
  the report.

Both modes also refuse one wording outright, which no rewrite of digits can
mend. Every surface the project has gave 523 as its count of standards: the
figure was ``counts.citation_groups``, citation strings cut at their first
colon or " Annex", so a book cited at seven clauses was seven standards, and
the citations named 227 normative designations and 125 further published
sources. :data:`FORBIDDEN` refuses a count of standards (``normas``) in any
sentence that speaks of conformance, checks or domains, in the prose this
script rewrites and in the generated files it does not (the report's own
headline, the agent files and the banner's words), and names the wording
that replaces it.

Run with ``python scripts/check_conformance_claims.py``; CI runs it alongside
the conformance regeneration gate.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import pathlib
import re
import sys
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

ROOT = pathlib.Path(__file__).resolve().parent.parent

#: Names of the ``counts`` fields the prose is allowed to quote, mapped to what
#: this script calls them. ``total`` is the historical name for the number of
#: checks and is kept because it is what the :data:`CLAIMS` table says. The
#: citation groups are not among them: no sentence may quote that figure.
FIELDS = {
    "checks": "total",
    "passing": "passing",
    "domains": "domains",
    "designations": "designations",
    "sources": "sources",
}

#: Prose patterns that assert a count. Each captures the number in group 1 and
#: names the report field it must equal. Both languages, since the Spanish
#: mirror carries the same claims.
#:
#: This tuple is the whole map of where the numbers live: the check reads it to
#: find stale values and the writer reads it to fix them, from the same entry,
#: with the same span. Adding a place a count is quoted means adding a pattern
#: here and nothing else.
#:
#: Every pattern is anchored to conformance wording. A bare "N domains" would
#: match any sentence in the corpus that happens to count domains for an
#: unrelated reason, so the domain count is only read where the claim's own
#: "across N domains" ("sobre N dominios", "en N dominios") phrasing writes it.
#: The designations and the further sources are read by their nouns, which
#: nothing else in the corpus counts. That covers the landing-page meta
#: descriptions too: Starlight frontmatter is static YAML, parsed before MDX
#: compiles, so it cannot interpolate an import, and the writer keeps those
#: strings current instead.
CLAIMS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"(\d+)\s+(?:numerical\s+)?conformance checks"), "total"),
    (re.compile(r"\ball\s+(\d+)\s+checks\b"), "total"),
    (re.compile(r"(\d+)\s+comprobaciones(?:\s+numéricas)?\s+de conformidad"), "total"),
    (re.compile(r"\blas\s+(\d+)\s+comprobaciones\b"), "total"),
    (re.compile(r"\bacross\s+(\d+)\s+domains\b"), "domains"),
    (re.compile(r"\b(?:en|sobre)\s+(\d+)\s+dominios\b"), "domains"),
    (re.compile(r"(\d+)\s+normative designations\b"), "designations"),
    (re.compile(r"(\d+)\s+further published sources\b"), "sources"),
    (re.compile(r"(\d+)\s+designaciones normativas\b"), "designations"),
    (re.compile(r"(\d+)\s+fuentes publicadas adicionales\b"), "sources"),
)

#: The claims as wrapped prose writes them, every space of a pattern a line
#: break too. The check and the writer read a claim line by line, so a count
#: wrapped away from its noun is one neither of them sees, and it goes stale
#: as silently as a typed one. These find it so it can be put back on a line.
WRAPPED: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pattern.pattern.replace(" ", r"\s+")), field)
    for pattern, field in CLAIMS
)

#: White space within one paragraph: a line may wrap between a count and its
#: noun, a blank line may not, since what follows it is another paragraph.
_GAP = r"(?:[ \t]+|[ \t]*\n[ \t]*)"

#: What may stand between a count and its noun: a list of issuing bodies, "N
#: IEC, ISO, EN, ANSI and VDI standards", or a word that says how the standards
#: were counted, "N referenced standards". A body is written in capitals, which
#: keeps a sentence that opens with "Las normas" after a heading ending in a
#: number out of the match.
_BODIES = (
    r"(?:(?:[A-Z][A-Z0-9/.-]+|and|y|referenced|cited|implemented|distinct"
    rf"|referenciadas|citadas|implementadas|distintas)(?:,{_GAP}?|{_GAP}))*"
)

#: A count of standards, in each language, mapped to the wording that replaces
#: it. Matched across line breaks, because prose wraps between a count and its
#: noun. Refused only inside a sentence :data:`CONFORMANCE_WORDING` finds,
#: so a page that counts the parts of a series for another reason is left alone.
FORBIDDEN: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(rf"\b\d+{_GAP}{_BODIES}standards\b"),
        "{designations} normative designations and {sources} further published sources",
    ),
    (
        re.compile(rf"\b\d+{_GAP}{_BODIES}normas\b"),
        "{designations} designaciones normativas y {sources} fuentes publicadas "
        "adicionales",
    ),
)

#: What makes a count of standards a conformance claim: the sentence it sits
#: in speaks of conformance, of checks or of domains.
CONFORMANCE_WORDING = re.compile(
    r"conformance|conformidad|\bchecks?\b|\bcomprobaci|\bdomains?\b|\bdominios?\b",
    re.IGNORECASE,
)

#: Where a sentence ends: a full stop, a question or exclamation mark before
#: white space, a blank line, or a paragraph tag of the HTML the Zenodo
#: description is written in.
_SENTENCE_END = re.compile(r"[.!?](?=\s)|\n[ \t]*\n|</?p>")

#: Generated files the count rewriting leaves alone and the refusal reads, as
#: paths and as ``(directory, glob)`` pairs: the report's own headline, the
#: agent files and the banner's words. A generator that wrote a count of
#: standards again would publish it in one of them.
GENERATED = ("docs/CONFORMANCE.md", "llms.txt", "llms-full.txt")
GENERATED_GLOBS = (("site/public/llms", "*.txt"), (".github/badges", "*.svg"))

#: Files whose counts are generated or quoted from a fixed historical context.
EXCLUDED_NAMES = (
    ("docs", "CONFORMANCE.md"),
    ("docs", "conformance.json"),
    ("CHANGELOG.md",),
    ("docs", "ERRATA.md"),
)

#: Directory names that never ship: local working notes, build output, vendored
#: dependencies. `docs/superpowers/` in particular is gitignored scratch space.
EXCLUDED_DIRS = frozenset({"superpowers", "node_modules", "dist", ".astro"})


@dataclasses.dataclass(frozen=True)
class Claim:
    """One quoted count, located precisely enough to rewrite it.

    :param field: Report field the number must equal (``total``, ``passing``,
        ``domains``, ``designations`` or ``sources``).
    :param claimed: The integer the prose states.
    :param start: Offset of the first digit within its line.
    :param end: Offset one past the last digit within its line.
    :param phrase: The whole matched phrase, for the diagnostic message.
    """

    field: str
    claimed: int
    start: int
    end: int
    phrase: str


def report_path(root: pathlib.Path = ROOT) -> pathlib.Path:
    """Path of the generated document that holds the authoritative counts."""
    return root / "docs" / "conformance.json"


def expected_counts(root: pathlib.Path = ROOT) -> dict[str, int]:
    """Read the authoritative counts out of the generated artefact.

    :param root: Repository root to read the artefact from.
    :return: Mapping of the names :data:`CLAIMS` uses to their values.
    :raises ValueError: If the artefact is missing, unreadable, or no longer
        carries one of the fields the claims are checked against.
    """
    report = report_path(root)
    try:
        counts = json.loads(_read(report))["counts"]
    except (OSError, ValueError, KeyError) as error:
        msg = (
            f"{_label(report, root)}: cannot read the conformance counts "
            f"({error}). Regenerate the artefact with `make conformance`."
        )
        raise ValueError(msg) from error
    missing = sorted(set(FIELDS) - set(counts))
    if missing:
        msg = (
            f"{_label(report, root)}: counts is missing {', '.join(missing)}. "
            "The artefact schema changed; update FIELDS here."
        )
        raise ValueError(msg)
    return {name: int(counts[field]) for field, name in FIELDS.items()}


def sources(root: pathlib.Path = ROOT) -> list[pathlib.Path]:
    """Every prose file that could quote a count.

    Four places, for four reasons.

    The guides and their site mirrors, walked from ``docs/`` and
    ``site/src/content/docs/``.

    The markdown at the repository root, non-recursively. This is where the
    two most-read pages of prose in the project live, and they were outside
    the walk: ``README.md``, and the ``README_PYPI.md`` generated from it,
    whose text is the PyPI long description. That one matters most of all,
    because PyPI freezes a description at upload, so a count that is stale
    when the release goes out is published wrong for good. The glob is
    deliberately not ``rglob``: recursing from the root would pull in
    ``stub/``, ``site/`` and every vendored tree under them.

    ``stub/README.md``, named rather than reached by a walk. It is the PyPI
    page of the PyOctaveBand transition package, frozen at its upload like the
    other one, and it sells the project on these same counts: it quoted the
    counts of 4.0.0rc1 for as long as nothing here read it.

    ``.zenodo.json``, because its description is prose too: it is the text the
    archived record shows, it states the counts, and it has no build step to
    interpolate them through.

    :param root: Repository root to walk.
    :return: The files to check or rewrite, in a stable order.
    """
    excluded = {root.joinpath(*parts) for parts in EXCLUDED_NAMES}
    roots = (root / "docs", root / "site" / "src" / "content" / "docs")
    found: list[pathlib.Path] = []
    for base in roots:
        if not base.is_dir():
            continue
        for pattern in ("*.md", "*.mdx"):
            found += sorted(base.rglob(pattern))
    found += sorted(root.glob("*.md"))
    stub = root / "stub" / "README.md"
    if stub.is_file():
        found.append(stub)
    kept = [
        path
        for path in found
        if path not in excluded and EXCLUDED_DIRS.isdisjoint(path.parts)
    ]
    zenodo = root / ".zenodo.json"
    if zenodo.is_file():
        kept.append(zenodo)
    return kept


def claims_in(line: str) -> list[Claim]:
    """Every count asserted by one line of prose.

    Patterns may overlap (two phrasings of one claim can read the same
    digits), so the same digits can be reported by more than one pattern.
    Identical spans are collapsed here; a span claimed for two different
    fields would make the map ambiguous and is rejected.

    :param line: A single line, without its line ending.
    :return: The claims found, ordered by position.
    :raises ValueError: If two patterns disagree about what a number means.
    """
    seen: dict[tuple[int, int], Claim] = {}
    for pattern, field in CLAIMS:
        for match in pattern.finditer(line):
            start, end = match.span(1)
            claim = Claim(field, int(match.group(1)), start, end, match.group(0))
            previous = seen.get((start, end))
            if previous is None:
                seen[(start, end)] = claim
            elif previous.field != field:
                msg = (
                    f"ambiguous conformance claim {line[start:end]!r}: "
                    f"read as {previous.field!r} by {previous.phrase!r} and as "
                    f"{field!r} by {match.group(0)!r}. Tighten one of the "
                    "patterns in CLAIMS."
                )
                raise ValueError(msg)
    return [seen[key] for key in sorted(seen)]


def rewrite_line(line: str, expected: Mapping[str, int]) -> tuple[str, list[Claim]]:
    """Set every count asserted by a line to its authoritative value.

    The substitution uses the span of the captured digits, never a textual
    replace: a blind ``str.replace`` of one integer for another rewrites every
    other number in the line that happens to share the value.

    :param line: A single line, with or without its line ending.
    :param expected: The authoritative counts.
    :return: The corrected line and the claims that had to be corrected.
    """
    ending_at = len(line.rstrip("\r\n"))
    body, ending = line[:ending_at], line[ending_at:]

    stale = [c for c in claims_in(body) if c.claimed != expected[c.field]]
    reach = len(body)
    for claim in reversed(stale):
        if claim.end > reach:
            msg = (
                f"overlapping conformance claims in {body!r}; the writer cannot "
                "rewrite spans that intersect."
            )
            raise ValueError(msg)
        reach = claim.start
        body = body[: claim.start] + str(expected[claim.field]) + body[claim.end :]
    return body + ending, stale


def rewrite_text(
    text: str, expected: Mapping[str, int]
) -> tuple[str, list[tuple[int, Claim]]]:
    """Apply :func:`rewrite_line` to a whole file, line endings preserved.

    :param text: The file's contents.
    :param expected: The authoritative counts.
    :return: The corrected text and the ``(line number, claim)`` pairs fixed.
    """
    out: list[str] = []
    fixed: list[tuple[int, Claim]] = []
    for lineno, line in enumerate(text.splitlines(keepends=True), start=1):
        corrected, stale = rewrite_line(line, expected)
        out.append(corrected)
        fixed += [(lineno, claim) for claim in stale]
    return "".join(out), fixed


def refused_in(text: str) -> list[tuple[int, str, str]]:
    """Every count of standards a text states as a conformance claim.

    :param text: A whole file, so that a count wrapped away from its noun, or
        from the conformance wording of its sentence, is still read.
    :return: ``(line number, phrase, replacement template)`` for each one, in
        the order they appear; the template names the report fields it needs.
    """
    found: list[tuple[int, str, str]] = []
    for pattern, replacement in FORBIDDEN:
        for match in pattern.finditer(text):
            if CONFORMANCE_WORDING.search(_sentence(text, *match.span())):
                lineno = text.count("\n", 0, match.start()) + 1
                found.append((lineno, " ".join(match.group(0).split()), replacement))
    return sorted(found)


def _sentence(text: str, start: int, end: int) -> str:
    """The sentence of ``text`` that holds the span ``start:end``."""
    head = 0
    for boundary in _SENTENCE_END.finditer(text, 0, start):
        head = boundary.end()
    tail = _SENTENCE_END.search(text, end)
    return text[head : tail.start() if tail else len(text)]


def wrapped_in(text: str) -> list[tuple[int, str]]:
    """Every claim a text wraps across a line break.

    :param text: A whole file.
    :return: ``(line number, phrase)`` for each one, in the order they appear.
    """
    found: set[tuple[int, str]] = set()
    for pattern, _ in WRAPPED:
        for match in pattern.finditer(text):
            if "\n" in match.group(0):
                lineno = text.count("\n", 0, match.start()) + 1
                found.add((lineno, " ".join(match.group(0).split())))
    return sorted(found)


def wrapped(root: pathlib.Path) -> list[str]:
    """Every claim of the corpus that the line-by-line reading cannot see.

    :param root: Repository root to read.
    :return: One printable diagnostic per wrapped claim.
    """
    return [
        f"{_label(path, root)}:{lineno}: {phrase!r} wraps a count away from its "
        "noun; keep them on one line"
        for path in sources(root)
        for lineno, phrase in wrapped_in(_read(path))
    ]


def generated_sources(root: pathlib.Path = ROOT) -> list[pathlib.Path]:
    """The generated files :func:`refusals` reads beside :func:`sources`.

    :param root: Repository root.
    :return: The ones that exist, in a stable order.
    """
    found = [root / name for name in GENERATED]
    for directory, pattern in GENERATED_GLOBS:
        found += sorted((root / directory).glob(pattern))
    return [path for path in found if path.is_file()]


def refusals(root: pathlib.Path, expected: Mapping[str, int]) -> list[str]:
    """Every count of standards published beside conformance wording.

    :param root: Repository root to read.
    :param expected: The authoritative counts, to name the replacement in.
    :return: One printable diagnostic per refused phrase.
    """
    problems: list[str] = []
    for path in [*sources(root), *generated_sources(root)]:
        problems += [
            f"{_label(path, root)}:{lineno}: counts standards in {phrase!r}; "
            "that figure counted citation groups, so state the split the "
            f"report makes: {replacement.format_map(expected)!r}"
            for lineno, phrase, replacement in refused_in(_read(path))
        ]
    return problems


def _read(path: pathlib.Path) -> str:
    """Read a file with its line endings left exactly as they are on disk.

    Decoded from its bytes rather than through ``read_text(newline="")``,
    which only Python 3.13 accepts: the bytes carry no newline translation
    either, and the script runs on every interpreter the package supports.
    """
    return path.read_bytes().decode("utf8")


def _label(path: pathlib.Path, root: pathlib.Path) -> str:
    """Repo-relative path in a form that reads the same on every platform."""
    return path.relative_to(root).as_posix()


def describe(label: str, lineno: int, claim: Claim, value: int) -> str:
    """One line of diagnostics about a stale claim."""
    return (
        f"{label}:{lineno}: claims {claim.claimed} {claim.field}, report says "
        f"{value} -> {claim.phrase!r}"
    )


def check(root: pathlib.Path, expected: Mapping[str, int]) -> list[str]:
    """Every stale count in the corpus, as printable diagnostics."""
    problems: list[str] = []
    for path in sources(root):
        _, fixed = rewrite_text(_read(path), expected)
        problems += [
            describe(_label(path, root), lineno, claim, expected[claim.field])
            for lineno, claim in fixed
        ]
    return problems


def write(root: pathlib.Path, expected: Mapping[str, int]) -> list[str]:
    """Bring every quoted count into line with the report.

    :param root: Repository root to rewrite in place.
    :param expected: The authoritative counts.
    :return: A printable description of each substitution made.
    """
    changes: list[str] = []
    for path in sources(root):
        text = _read(path)
        corrected, fixed = rewrite_text(text, expected)
        if not fixed:
            continue
        # `newline=""` on both ends: the file keeps whatever line endings it
        # already had, so a rewrite is a change of digits and nothing else.
        path.write_text(corrected, encoding="utf8", newline="")
        changes += [
            f"{_label(path, root)}:{lineno}: {claim.claimed} -> "
            f"{expected[claim.field]} {claim.field} in {claim.phrase!r}"
            for lineno, claim in fixed
        ]
    return changes


def main(argv: Sequence[str] | None = None) -> int:
    """Check, or with ``--write`` correct, the counts quoted in the prose."""
    parser = argparse.ArgumentParser(
        description=(
            "Check that every conformance count quoted in the docs, the root "
            "READMEs, the site frontmatter and .zenodo.json equals the "
            "counts recorded in docs/conformance.json."
        )
    )
    parser.add_argument(
        "--write",
        "--fix",
        action="store_true",
        help=(
            "rewrite the quoted counts in place instead of only reporting "
            "them. Only the digits of a matched claim are replaced."
        ),
    )
    parser.add_argument(
        "--root",
        type=pathlib.Path,
        default=ROOT,
        help="repository root to operate on (default: this checkout)",
    )
    args = parser.parse_args(argv)
    root: pathlib.Path = args.root.resolve()

    # Every failure that means "the CLAIMS table or the report format needs
    # attention" surfaces as a ValueError: a report whose headline no longer
    # parses, a number two patterns read differently, spans that intersect.
    # They are all editing mistakes, so they get the same one-line diagnostic
    # rather than a traceback.
    try:
        return _run(writing=args.write, root=root)
    except ValueError as error:
        print(error, file=sys.stderr)
        return 1


def _run(*, writing: bool, root: pathlib.Path) -> int:
    """Body of :func:`main`, once the arguments are settled."""
    expected = expected_counts(root)
    summary = (
        f"{expected['total']} checks, {expected['domains']} domains, "
        f"{expected['designations']} normative designations, "
        f"{expected['sources']} further published sources"
    )

    changes = write(root, expected) if writing else []
    for change in changes:
        print(f"  {change}")
    stale = _report(
        (
            "Counts still stale after rewriting. A claim was matched but could "
            "not be corrected:"
        )
        if writing
        else (
            "Stale conformance counts. docs/conformance.json is the authority; "
            "regenerate it and rewrite the prose with `make conformance` "
            "(which runs this script with --write), or fix the wording so the "
            "claim is matched:"
        ),
        check(root, expected),
    )
    hidden = _report(
        "Conformance counts wrapped across two lines, which neither the check "
        "nor the writer reads:",
        wrapped(root),
    )
    refused = _report(
        "Counts of standards beside conformance wording. No rewrite of digits "
        "mends these; change the wording:",
        refusals(root, expected),
    )
    if stale or hidden or refused:
        return 1

    if not writing:
        print(f"Conformance claims consistent: {summary}.")
    elif changes:
        print(f"Rewrote {len(changes)} conformance count(s) from ", end="")
        print(f"docs/conformance.json: {summary}.")
    else:
        print(
            f"Conformance claims already consistent with docs/conformance.json: {summary}."
        )
    return 0


def _report(header: str, problems: Sequence[str]) -> bool:
    """Print ``problems`` under ``header`` on stderr; say whether there were any."""
    if problems:
        print(f"{header}\n", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
    return bool(problems)


if __name__ == "__main__":
    raise SystemExit(main())
