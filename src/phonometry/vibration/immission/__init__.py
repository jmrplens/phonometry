"""vibration.immission subdomain of phonometry: measuring vibration immission.

The German immission-control chain: DIN 45669-1 defines the vibration meter
that DIN 4150-2 and DIN 4150-3 presuppose, and its Annex E turns the
frequency-dependent guideline curve of DIN 4150-3 into a comparison with one
number. DIN 45669-2 is the procedure the meter is used with, of which the
mounting limits and the instrument's share of the error are numbers, and
DIN 4150-2 is what the meter's readings are judged by for the people in the
building. DIN 45672-2 reduces the record of a passing train with that meter,
and Clause 4.5 of DIN 45672-1 reads the elastic constants of the ground from
its wave speeds.
"""

