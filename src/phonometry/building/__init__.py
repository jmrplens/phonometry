"""building domain of phonometry (see module docstrings).

Three subgroups since 4.0, by what the acoustician is doing: measuring a
building that exists (:mod:`~phonometry.building.measurement`, the ISO 16283,
10140, 10052, 15186 and 10848 methods with their ISO 717 ratings and ISO 12999
uncertainty), predicting one that does not yet
(:mod:`~phonometry.building.prediction`, EN 12354 and the panel theory behind
it) and checking either against a national code
(:mod:`~phonometry.building.regulation`). Every public name is still exported
here, so ``from phonometry import building`` reads as it did.
"""

