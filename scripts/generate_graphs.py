"""Regenerate every documentation figure and animation, in all four variants.

The command line of the :mod:`figures` package -- ``make graphs``,
``make animations`` and ``make posters`` all run this file -- and the facade
that keeps its old namespace: the generators moved into
``scripts/figures/``, grouped by the subject of the guide that embeds them,
and every one of them is re-exported here, so ``import generate_graphs``
still finds every figure this file used to define. What is *not* re-exported
is what it never defined: the names it happened to expose because it imported
them (``np``, ``plt``, ``OctaveFilterBank`` and the rest), which now belong to
the module that needs them.

The first import is :mod:`figures` itself, whose ``__init__`` pins the
numerical thread pools before numpy, scipy or numba can import a
multi-threaded backend; that is what keeps the rendered bytes identical
across machines, so nothing numerical may be imported above it.
"""

